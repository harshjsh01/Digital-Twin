"""
Project Aahavaan – Phase 2 state-transition synthetic generator.

The target is generated by advancing a simplified railway operational state
15 minutes into the future. This is deliberately different from simply
copying current delay into the target.
"""

from pathlib import Path
import argparse
import numpy as np
import pandas as pd

TRAIN = {
    "Vande Bharat": (160, 720, 1.00, 2),
    "Rajdhani": (130, 720, 0.95, 3),
    "Superfast": (120, 600, 0.85, 4),
    "Mail Express": (110, 550, 0.70, 5),
    "Freight": (60, 650, 0.40, 8),
}
WEATHER = ["Clear", "Cloudy", "Rain", "Fog"]
WP = [0.62, 0.18, 0.14, 0.06]
CORRIDORS = [("Delhi-Kanpur", 440), ("Howrah-Delhi", 1450)]


def disturbance(rng, train_type, stress):
    if train_type == "Freight":
        return rng.weibull(1.35) * (2.0 + 2.0*stress) + rng.gamma(1.8, 1.0)
    return rng.weibull(1.9) * (0.6 + 0.8*stress) + rng.gamma(2.2, 0.55)


def generate_dataset(scenarios=500, snapshots_per_train=8, seed=42, output_path=None):
    rng = np.random.default_rng(seed)
    rows = []

    types = (["Vande Bharat"]*8 + ["Rajdhani"]*8 + ["Superfast"]*14
             + ["Mail Express"]*14 + ["Freight"]*16)

    for sid in range(1, scenarios+1):
        corridor, corridor_km = CORRIDORS[rng.integers(0, len(CORRIDORS))]
        weather = rng.choice(WEATHER, p=WP)
        freight_surge = int(rng.random() < 0.15)
        failure = int(rng.random() < 0.06)

        weather_level = {"Clear":0, "Cloudy":1, "Rain":2, "Fog":3}[weather]
        weather_factor = {"Clear":1.0, "Cloudy":1.08, "Rain":1.35, "Fog":1.8}[weather]

        shuffled = types.copy()
        rng.shuffle(shuffled)
        departures = np.sort(rng.uniform(0, 1440, 60))

        for i, train_type in enumerate(shuffled):
            max_speed, length, priority, dwell = TRAIN[train_type]
            sched_dep = float(departures[i])
            headway = float(rng.uniform(8,25) if i == 0 else
                            max(2, departures[i]-departures[i-1]))

            # Initial state.
            delay = max(
                0,
                disturbance(rng, train_type, weather_level/3)
                * weather_factor
                * (1.45 if freight_surge else 1)
                * (2.0 if failure else 1)
                + rng.normal(0, 0.7)
            )

            queue = int(np.clip(
                rng.poisson(1.2 + 0.07*max(0,10-headway)
                            + 2*freight_surge + 3*failure), 0, 12))
            platform = int(np.clip(
                rng.poisson(1.1 + .20*queue + freight_surge), 0, 6))

            for snap in range(snapshots_per_train):
                current_time = (sched_dep + snap*15 + rng.uniform(-2,2)) % 1440
                distance = float(rng.uniform(8, min(45, corridor_km/8)))
                gradient = float(np.clip(rng.normal(0,5), -18,18))

                # Current operational state.
                current_speed = max(
                    5,
                    max_speed * (1 - .055*queue - .045*max(0,platform-2))
                    * (0.82 if weather == "Fog" else 1)
                    + rng.normal(0,5)
                )
                current_speed = min(current_speed, max_speed)

                # Simulate one 15-minute state transition.
                capacity_pressure = (
                    .55*queue
                    + .45*max(0, platform-2)
                    + .35*max(0, 10-headway)
                )
                gradient_effect = .025*abs(gradient)
                weather_effect = {"Clear":0, "Cloudy":.15, "Rain":.7, "Fog":1.8}[weather]
                failure_effect = 2.8 if failure and rng.random() < .45 else 0

                # New queue after 15 minutes: arrivals, departures and disturbances.
                queue_change = (
                    rng.poisson(.8 + .08*max(0, platform-3))
                    - rng.binomial(queue, .28) if queue > 0
                    else rng.poisson(.8)
                )
                future_queue = int(np.clip(queue + queue_change +
                                           (1 if failure and rng.random()<.5 else 0), 0, 12))

                platform_change = rng.choice([-1,0,0,1], p=[.12,.48,.28,.12])
                future_platform = int(np.clip(platform + platform_change +
                                               (1 if future_queue > 7 else 0), 0, 6))

                run_time = 60*distance/max(current_speed, 5)
                nominal_time = 60*distance/max_speed

                # Future delay state transition.
                delay_increment = (
                    .16*delay
                    + .38*capacity_pressure
                    + .16*future_queue
                    + .20*max(0, future_platform-3)
                    + gradient_effect
                    + weather_effect
                    + failure_effect
                    + .12*dwell
                    + .006*max(0, run_time-nominal_time)*10
                    + disturbance(rng, train_type, weather_level/3)*.55
                    - .35*priority
                )
                future_delay = float(np.clip(
                    delay + delay_increment + rng.normal(0, .7), 0, 90
                ))

                rows.append({
                    "Scenario_ID": sid,
                    "Corridor": corridor,
                    "Train_ID": f"T{sid:04d}_{i+1:03d}",
                    "Train_Type": train_type,
                    "Priority_Weight": priority,
                    "Train_Length_M": length,
                    "Section_Distance_KM": round(distance,3),
                    "Max_Permissible_Speed": max_speed,
                    "Scheduled_Dwell_Min": dwell,
                    "Current_Delay_Min": round(delay,3),
                    "Preceding_Headway_Min": round(headway,3),
                    "Sectional_Gradient_Pct": round(gradient,3),
                    "Weather": weather,
                    "Outer_Signal_Queue_Depth": queue,
                    "Platform_Occupancy_State": platform,
                    "Freight_Surge": freight_surge,
                    "Infrastructure_Failure": failure,
                    "Current_Time_Min": round(current_time,3),
                    "Scheduled_Departure_Min": round(sched_dep,3),
                    "Future_Horizon_Min": 15,
                    "Future_Delay_15Min": round(future_delay,3),
                    # State-transition audit columns.
                    "Future_Signal_Queue_Depth": future_queue,
                    "Future_Platform_Occupancy_State": future_platform,
                })

                # Advance state for next snapshot.
                delay = future_delay
                queue = future_queue
                platform = future_platform
                headway = max(
                    2,
                    headway + rng.normal(0,1.5) + .15*(queue-3)
                )

    df = pd.DataFrame(rows)
    if output_path:
        Path(output_path).parent.mkdir(parents=True, exist_ok=True)
        df.to_csv(output_path, index=False)
    return df


if __name__ == "__main__":
    p = argparse.ArgumentParser()
    p.add_argument("--scenarios", type=int, default=500)
    p.add_argument("--snapshots", type=int, default=8)
    p.add_argument("--seed", type=int, default=42)
    p.add_argument("--output", default="models/datasets/processed/phase2_train_delay_dataset.csv")
    a = p.parse_args()
    d = generate_dataset(a.scenarios,a.snapshots,a.seed,a.output)
    print(f"Rows: {len(d):,} | Columns: {len(d.columns)}")
    print(d["Future_Delay_15Min"].describe())
